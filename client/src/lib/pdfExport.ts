import jsPDF from "jspdf";

// ─── Scene section pagination ───────────────────────────────────────────────
type ScenePage = {
  pageW: number;
  pageH: number;
  margin: number;
  orientation: "landscape" | "portrait";
};

type SceneSection = {
  label: string;
  text: string;
  labelSize: number;
  bodySize: number;
  lineHeight: number;
  labelGap: number;
  afterGap: number;
  color: [number, number, number];
};

const SECTION_LABEL_COLOR: [number, number, number] = [100, 90, 150];

// doc.text draws at the alphabetic baseline, so the first line on a page is
// inset by the glyph ascent to keep it below the top margin.
function fontAscent(doc: jsPDF, size: number): number {
  return (size / doc.internal.scaleFactor) * 0.8;
}

function addScenePage(doc: jsPDF, page: ScenePage) {
  doc.addPage("a4", page.orientation);
  doc.setFillColor(15, 15, 25);
  doc.rect(0, 0, page.pageW, page.pageH, "F");
}

// Draws a labelled, wrapped section starting at baseline y, continuing onto new
// pages as needed. Returns the baseline for the next section.
function addSceneSection(doc: jsPDF, page: ScenePage, y: number, section: SceneSection): number {
  const bottom = page.pageH - page.margin;
  doc.setFontSize(section.bodySize);
  const lines: string[] = doc.splitTextToSize(section.text, page.pageW - page.margin * 2);

  // Keep the label with its first content line.
  if (y + section.labelGap + section.lineHeight > bottom) {
    addScenePage(doc, page);
    y = page.margin + fontAscent(doc, section.labelSize);
  }
  doc.setFontSize(section.labelSize);
  doc.setTextColor(...SECTION_LABEL_COLOR);
  doc.text(section.label, page.margin, y);
  y += section.labelGap;

  doc.setFontSize(section.bodySize);
  doc.setTextColor(...section.color);
  for (let i = 0; i < lines.length; i++) {
    if (i > 0 && y + section.lineHeight > bottom) {
      addScenePage(doc, page);
      doc.setFontSize(section.bodySize);
      doc.setTextColor(...section.color);
      y = page.margin + fontAscent(doc, section.bodySize);
    }
    doc.text(lines[i], page.margin, y);
    y += section.lineHeight;
  }
  return y + section.afterGap;
}

// ─── Storyboard PDF ─────────────────────────────────────────────────────────
export function exportStoryboardPdf(data: {
  title: string;
  synopsis?: string;
  totalDuration?: number;
  style?: string;
  scenes: Array<{
    sceneNumber: number;
    duration: number;
    cameraAngle: string;
    cameraMovement: string;
    visualDescription: string;
    narration?: string;
    mood: string;
    transition: string;
    imageUrl?: string;
  }>;
}) {
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 15;
  const scenePage: ScenePage = { pageW, pageH, margin, orientation: "landscape" };

  // Title page
  doc.setFillColor(15, 15, 25);
  doc.rect(0, 0, pageW, pageH, "F");

  doc.setTextColor(200, 180, 255);
  doc.setFontSize(32);
  doc.text(data.title || "Storyboard", pageW / 2, 60, { align: "center" });

  if (data.synopsis) {
    doc.setFontSize(12);
    doc.setTextColor(160, 160, 180);
    const synLines = doc.splitTextToSize(data.synopsis, pageW - margin * 4);
    doc.text(synLines, pageW / 2, 80, { align: "center" });
  }

  doc.setFontSize(10);
  doc.setTextColor(120, 120, 140);
  const meta: string[] = [];
  if (data.style) meta.push(`Style: ${data.style}`);
  if (data.totalDuration) meta.push(`Duration: ${data.totalDuration}s`);
  meta.push(`Scenes: ${data.scenes.length}`);
  doc.text(meta.join("  |  "), pageW / 2, 100, { align: "center" });

  doc.setFontSize(8);
  doc.setTextColor(80, 80, 100);
  doc.text(`Generated by DreamForgeX Video Studio  •  ${new Date().toLocaleDateString()}`, pageW / 2, pageH - 15, { align: "center" });

  // Scene pages
  for (const scene of data.scenes) {
    addScenePage(doc, scenePage);

    // Scene header
    doc.setFillColor(40, 30, 80);
    doc.roundedRect(margin, margin, pageW - margin * 2, 14, 3, 3, "F");
    doc.setTextColor(200, 180, 255);
    doc.setFontSize(14);
    doc.text(`Scene ${scene.sceneNumber}`, margin + 5, margin + 9);

    doc.setFontSize(9);
    doc.setTextColor(160, 160, 180);
    const headerInfo = [`${scene.duration}s`, scene.mood, scene.transition].filter(Boolean).join("  •  ");
    doc.text(headerInfo, pageW - margin - 5, margin + 9, { align: "right" });

    let y = margin + 22;

    y = addSceneSection(doc, scenePage, y, {
      label: "VISUAL DESCRIPTION",
      text: scene.visualDescription,
      labelSize: 8,
      bodySize: 10,
      lineHeight: 5,
      labelGap: 5,
      afterGap: 6,
      color: [220, 220, 230],
    });

    y = addSceneSection(doc, scenePage, y, {
      label: "CAMERA",
      text: `Angle: ${scene.cameraAngle}  |  Movement: ${scene.cameraMovement}`,
      labelSize: 8,
      bodySize: 9,
      lineHeight: 4.5,
      labelGap: 5,
      afterGap: 3.5,
      color: [180, 180, 200],
    });

    if (scene.narration) {
      y = addSceneSection(doc, scenePage, y, {
        label: "NARRATION",
        text: `"${scene.narration}"`,
        labelSize: 8,
        bodySize: 9,
        lineHeight: 4.5,
        labelGap: 5,
        afterGap: 6,
        color: [180, 170, 130],
      });
    }

    addSceneSection(doc, scenePage, y, {
      label: "MOOD & TRANSITION",
      text: `Mood: ${scene.mood}  |  Transition: ${scene.transition}`,
      labelSize: 8,
      bodySize: 9,
      lineHeight: 4.5,
      labelGap: 5,
      afterGap: 0,
      color: [180, 180, 200],
    });
  }

  doc.save(`${(data.title || "storyboard").replace(/[^a-zA-Z0-9]/g, "-").toLowerCase()}.pdf`);
}

// ─── Script PDF ─────────────────────────────────────────────────────────────
export function exportScriptPdf(data: {
  title: string;
  logline?: string;
  targetDuration?: number;
  format?: string;
  tone?: string;
  productionBudget?: string;
  equipmentNeeded?: string[];
  scenes: Array<{
    sceneNumber: number;
    startTime: string;
    endTime: string;
    location: string;
    visualDescription: string;
    cameraDirection: string;
    narration?: string;
    dialogue?: string;
    soundDesign?: string;
    productionNotes?: string;
  }>;
}) {
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 20;
  const contentW = pageW - margin * 2;
  const scenePage: ScenePage = { pageW, pageH, margin, orientation: "portrait" };

  // Title page
  doc.setFillColor(15, 15, 25);
  doc.rect(0, 0, pageW, pageH, "F");

  doc.setTextColor(200, 180, 255);
  doc.setFontSize(28);
  doc.text(data.title || "Video Script", pageW / 2, 80, { align: "center" });

  if (data.logline) {
    doc.setFontSize(11);
    doc.setTextColor(160, 160, 180);
    const logLines = doc.splitTextToSize(data.logline, contentW);
    doc.text(logLines, pageW / 2, 95, { align: "center" });
  }

  doc.setFontSize(9);
  doc.setTextColor(120, 120, 140);
  const meta: string[] = [];
  if (data.format) meta.push(`Format: ${data.format}`);
  if (data.tone) meta.push(`Tone: ${data.tone}`);
  if (data.targetDuration) meta.push(`Duration: ${data.targetDuration}s`);
  meta.push(`Scenes: ${data.scenes.length}`);
  doc.text(meta.join("  |  "), pageW / 2, 115, { align: "center" });

  if (data.productionBudget) {
    doc.setFontSize(9);
    doc.setTextColor(100, 100, 120);
    doc.text(`Budget: ${data.productionBudget}`, pageW / 2, 125, { align: "center" });
  }

  doc.setFontSize(8);
  doc.setTextColor(80, 80, 100);
  doc.text(`Generated by DreamForgeX Video Studio  •  ${new Date().toLocaleDateString()}`, pageW / 2, pageH - 15, { align: "center" });

  // Scene pages
  for (const scene of data.scenes) {
    addScenePage(doc, scenePage);

    // Scene header bar
    doc.setFillColor(40, 30, 80);
    doc.roundedRect(margin, margin, contentW, 16, 3, 3, "F");
    doc.setTextColor(200, 180, 255);
    doc.setFontSize(12);
    doc.text(`SCENE ${scene.sceneNumber}`, margin + 5, margin + 10);
    doc.setFontSize(8);
    doc.setTextColor(160, 160, 180);
    doc.text(`${scene.startTime} — ${scene.endTime}  |  ${scene.location}`, pageW - margin - 5, margin + 10, { align: "right" });

    let y = margin + 24;

    const addSection = (label: string, text: string, color: [number, number, number] = [220, 220, 230]) => {
      y = addSceneSection(doc, scenePage, y, {
        label,
        text,
        labelSize: 7,
        bodySize: 9,
        lineHeight: 4.5,
        labelGap: 4,
        afterGap: 6,
        color,
      });
    };

    addSection("VISUAL DESCRIPTION", scene.visualDescription);
    addSection("CAMERA DIRECTION", scene.cameraDirection, [180, 200, 220]);

    if (scene.narration) {
      addSection("NARRATION", `"${scene.narration}"`, [180, 170, 130]);
    }
    if (scene.dialogue) {
      addSection("DIALOGUE", scene.dialogue, [170, 180, 200]);
    }
    if (scene.soundDesign) {
      addSection("SOUND DESIGN", scene.soundDesign, [150, 160, 170]);
    }
    if (scene.productionNotes) {
      addSection("PRODUCTION NOTES", scene.productionNotes, [140, 140, 160]);
    }
  }

  // Equipment page
  if (data.equipmentNeeded && data.equipmentNeeded.length > 0) {
    doc.addPage("a4", "portrait");
    doc.setFillColor(15, 15, 25);
    doc.rect(0, 0, pageW, pageH, "F");

    doc.setTextColor(200, 180, 255);
    doc.setFontSize(16);
    doc.text("Equipment & Production", margin, margin + 10);

    let y = margin + 20;
    doc.setFontSize(9);
    doc.setTextColor(180, 180, 200);
    for (const eq of data.equipmentNeeded) {
      doc.text(`•  ${eq}`, margin + 5, y);
      y += 6;
    }

    if (data.productionBudget) {
      y += 6;
      doc.setFontSize(8);
      doc.setTextColor(100, 90, 150);
      doc.text("BUDGET ESTIMATE", margin, y);
      y += 5;
      doc.setFontSize(9);
      doc.setTextColor(180, 180, 200);
      doc.text(data.productionBudget, margin, y);
    }
  }

  doc.save(`${(data.title || "script").replace(/[^a-zA-Z0-9]/g, "-").toLowerCase()}.pdf`);
}
